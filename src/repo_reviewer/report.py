"""Render a Review as Markdown or JSON."""

from __future__ import annotations

import json
from dataclasses import asdict

from .agent import Review

BADGE = {"high": "🔴 High", "medium": "🟠 Medium", "low": "🟢 Low"}


def to_markdown(review: Review, repo_name: str) -> str:
    counts = {s: sum(f.severity == s for f in review.findings) for s in ("high", "medium", "low")}
    out = [
        f"# Code review: {repo_name}",
        "",
        f"**Findings:** {counts['high']} high · {counts['medium']} medium · {counts['low']} low",
        "",
        "## Summary",
        review.summary,
        "",
        "## Architecture",
        review.architecture,
        "",
    ]
    if review.strengths:
        out += ["## Strengths", *[f"- {s}" for s in review.strengths], ""]

    out.append("## Findings")
    if not review.findings:
        out.append("No issues found.")
    for i, f in enumerate(review.findings, 1):
        loc = f"`{f.file}:{f.line}`" if f.line else f"`{f.file}`"
        out += [
            "",
            f"### {i}. {f.title}",
            f"{BADGE.get(f.severity, f.severity)} · {f.category} · {loc}",
            "",
            f.detail,
            "",
            f"**Suggestion:** {f.suggestion}",
        ]

    calls = ", ".join(f"{k} ×{v}" for k, v in sorted(review.tool_calls.items())) or "none"
    out += [
        "",
        "---",
        f"<sub>Generated by repo-reviewer · model `{review.model}` · {review.turns} turns · "
        f"tools: {calls} · tokens: {review.input_tokens:,} in / {review.output_tokens:,} out</sub>",
        "",
    ]
    return "\n".join(out)


def to_json(review: Review) -> str:
    return json.dumps(asdict(review), indent=2, ensure_ascii=False)
